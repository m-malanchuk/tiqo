def filter_emojis(query: str) -> list[EmojiItem]:
    q = query.strip().lower()
    if q.startswith(":") and q.endswith(":") and len(q) > 2:
        q = q[1:-1]
    elif q.startswith(":"):
        q = q[1:]
    if not q:
        return list(EMOJI_CATALOG)
    out: list[EmojiItem] = []
    for item in EMOJI_CATALOG:
        if q in item.glyph:
            out.append(item)
            continue
        if any(q in code for code in item.shortcodes):
            out.append(item)
    return out
